HERE = os.path.dirname(os.path.abspath(__file__)); FAMD = os.path.abspath(f"{HERE}/../family"); IM = os.path.abspath(f"{HERE}/../images")
sys.path.insert(0, HERE); sys.path.insert(0, FAMD); sys.path.insert(0, os.path.abspath(f"{HERE}/../scripts"))
from PIL import Image, ImageDraw
TW, TH = 370, 230
BLUE = (0, 70, 220)
def tile(win, label, marker_x, above=False):
    c = Image.new("RGB", (TW, TH), "white"); top = 22 if above else 0; c.paste(win, (5, top)); d = ImageDraw.Draw(c); mx = 5 + marker_x
    if above: d.polygon([(mx - 9, 3), (mx + 9, 3), (mx, 19)], fill=BLUE)
    else:
        y = win.height; d.polygon([(mx - 9, y + 17), (mx + 9, y + 17), (mx, y + 2)], fill=BLUE)
    d.text((6, TH - 14), label, fill=(0, 0, 0)); return c
def band_win(path, x, half=110, scale=1.6):
    im = Image.open(path).convert("RGB"); x0 = max(0, min(im.width - 2 * half, x - half)); w = im.crop((x0, 0, x0 + 2 * half, im.height))
    s = min(scale, 360 / w.width, 190 / w.height); return w.resize((int(w.width * s), int(w.height * s))), int((x - x0) * s)
def sheets(ims, prefix, scratch):
    out = []
    for s in range(0, len(ims), 20):
        sh = Image.new("RGB", (4 * TW, 5 * TH), "white")
        for k, c in enumerate(ims[s:s + 20]): sh.paste(c, ((k % 4) * TW, (k // 4) * TH))
        f = f"{scratch}/v6/{prefix}_{s // 20 + 1:02d}.jpg"; sh.save(f, quality=90); out.append(f)
    return out
def main(scratch):
    import h193_attr as H, h199_bowl_108v as h199, h202_bowl_108r as h202, json
    from align_check import fam
    os.makedirs(f"{scratch}/v6", exist_ok=True); g = H.g
    key = ["item\tcall\tset\tleaf\tline\tsegment\tx_px\tcode\tletter\tsource"]
    h193 = list(g.rd(f"{FAMD}/h193_items.tsv"))
    # K: runner's anchor strips cut out of the runner's sheets (Qnn at sheet (n-1)//20, cell (n-1)%20 of a 4x5 grid of 370x190)
    ks = [r for r in h193 if r["group"] in ("CP", "AN")]; random.Random(605).shuffle(ks); kims = []
    for n, r in enumerate(ks, 1):
        q = int(r["item"][1:]) - 1; sh = Image.open(f"{scratch}/h193/sheet_{q // 20 + 1:02d}.jpg"); k = q % 20
        t = sh.crop(((k % 4) * 370, (k // 4) * 190, (k % 4) * 370 + 370, (k // 4) * 190 + 172)); c = Image.new("RGB", (370, 190), "white"); c.paste(t, (0, 0))
        ImageDraw.Draw(c).text((6, 174), f"K{n:02d}", fill=(0, 0, 0)); kims.append(c)
        key.append(f"K{n:02d}\tall\tK\t176v\t{r['line']}\t{r['segment']}\t{r['x_px']}\t-\t{r['letter']}\t{r['group']} (runner strip {r['item']})")
    sh = Image.new("RGB", (4 * 370, 5 * 190), "white")
    for k, c in enumerate(kims): sh.paste(c, ((k % 4) * 370, (k // 4) * 190))
    sh.save(f"{scratch}/v6/control_K.jpg", quality=90)
    def fa_items():
        return [dict(set="FA", leaf="176v", line=r["line"], segment=r["segment"], x=int(r["x_px"]), code="-", letter=r["letter"], src=r["group"],
                     path=f"{scratch}/f176v/f176v_{r['line']}_{r['segment']}.jpg") for r in h193 if r["group"] in ("CP", "AN")]
    # call 1: f.176r
    import glob
    lines = {}
    for f in sorted(glob.glob(f"{H.b.P}/f177v_clearA_*.tsv")):
        for r in g.rd(f): lines.setdefault("V" + r["line"].lstrip("LV"), r["text"])
    sr, orr = H.cons_origin(H.rows_full("f176r_signsA_*.tsv"), H.rows_full("f176r_signsB_*.tsv"), [f"L{k:02d}" for k in range(1, 48)])
    tr = H.v.clear177r() + "".join(g.fold(lines[f"V{k:02d}"]) for k in range(1, 6)); tr = tr[:len(sr)]
    pr = H.paired(sr, orr, tr); tset = {(r["line"], r["segment"], int(r["x_px"])) for r in h193 if r["group"] == "T"}
    rt = [dict(set="RT", leaf="176r", line=r["line"], segment=r["segment"], x=int(r["x_px"]), code="4TRI", letter=r["letter"], src=r["item"],
               path=f"{scratch}/f176r/f176_{r['line']}_{r['segment']}.jpg") for r in h193 if r["group"] == "T"]
