"""VERIFY-F61-V6 (29 Sept 2026) task 1: the bowl question re-run blind on the verifier's own crops. Written before any vision call.
 tiles SCRATCH  cuts every item in a framing different from the runner's (narrower window, larger scale, BLUE marker, own seeds) and writes
                items_v6.tsv (item -> call, set, leaf, position, code, letter where one exists). Letters never appear on a sheet.
   call 1: control K01-K20 = the runner's own H193 anchor strips, cut out of <SCRATCH>/h193/sheet_0*.jpg (regenerated by h193_attr.py
           tiles, h193_items.tsv reproduced byte-identical) on a sheet of their own;
           plus, mixed and shuffled (seed 606): the same 20 f.176v anchors re-cut in the verifier's framing (set FA), H193's 40 f.176r targets
           re-cut (set RT), and 40 fresh f.176r 4-family columns of ANY reader code paired with c/p (20) or a/n (20) under the runner's
           alignment (key v4, whose 4TRI set a/c/n/p/t cannot favour c/p over a/n), H193 targets excluded (set RN, seed 606).
   call 2: K01-K20 again; FA again (reshuffled, seed 607) mixed with f.108v's 74 H199 columns (set V8) and f.108r's 20 H202 gloss positions
           (set R8), each re-cut (f.108v from the native, marker ABOVE because the leaf's gloss sits below; f.108r from images/f108sheetB).
   call 3: K01-K20 again; FA again (seed 608); the six f.61 span lines (L01 L03 L05 L07 L08 L11) re-cut by the verifier from the native
           region (slope fits from tools/iiif_lines.py, two halves per line with no overlap, 1.3x), the reader lists every figure-4-shaped
           sign left to right and answers the bowl question for each (H194's list method; a line whose listed count differs from its
           4-family code count is left out).
 score (score_v6.py) GATE per call: K >= 17/20 (the runner's gate on the runner's strips) AND FA >= 17/20; else that call's targets are
   not scored.
  python3 tiles_v6.py tiles SCRATCH"""
